#!/usr/bin/env node
/*
 * CPU opcode self-test: for all 256 opcodes verify instruction length and
 * base cycle count against an independent reference table (official NMOS 6502
 * + common unofficial), plus behavior spot checks for arithmetic/logic ops.
 */
'use strict';
const CPU = require('../js/cpu.js');

// reference: opcode -> [length, cycles] (cycles exclude page-cross/branch extras)
const LEN = {}; const CYC = {};
function r(ops, len, cyc) { for (const op of ops) { LEN[op] = len; CYC[op] = cyc; } }
r([0x00],2,7); // BRK consumes 2 bytes
r([0x08,0x18,0x28,0x38,0x48,0x58,0x68,0x78,0x88,0x98,0xA8,0xB8,0xC8,0xD8,0xE8,0xF8,
   0x8A,0x9A,0xAA,0xBA,0xCA,0xDA,0xEA,0xFA,0x1A,0x3A,0x5A,0x7A],1,2);
LEN[0x08]=1;CYC[0x08]=3;LEN[0x48]=1;CYC[0x48]=3;LEN[0x68]=1;CYC[0x68]=4;LEN[0x28]=1;CYC[0x28]=4;
LEN[0x40]=1;CYC[0x40]=6;LEN[0x60]=1;CYC[0x60]=6;
LEN[0x0A]=1;CYC[0x0A]=2;LEN[0x2A]=1;CYC[0x2A]=2;
LEN[0x4A]=1;CYC[0x4A]=2;LEN[0x6A]=1;CYC[0x6A]=2;

// imm
r([0x09,0x29,0x49,0x69,0xA9,0xC9,0xE9],2,2);
r([0xA2,0xA0,0xC0,0xE0,0xEB],2,2);
r([0x0B,0x2B,0x4B,0x6B,0x8B,0xAB,0xCB],2,2); // unofficial imm
r([0x80,0x82,0x89,0xC2,0xE2],2,2); // NOP imm
// zp
r([0x05,0x25,0x45,0x65,0xA5,0xC5,0xE5],2,3);
r([0xA6,0xA4,0xC4,0xE4],2,3);
r([0x85,0x86,0x84,0x87],2,3);
r([0x06,0x26,0x46,0x66,0xC6,0xE6],2,5);
r([0x24],2,3);
r([0x07,0x27,0x47,0x67,0xC7,0xE7],2,5);
r([0xA7,0x04,0x44,0x64],2,3);
// zp,x / zp,y
r([0x15,0x35,0x55,0x75,0xB5,0xD5,0xF5,0xB4,0x94,0x14,0x34,0x54,0x74,0xD4,0xF4],2,4);
r([0x17,0x37,0x57,0x77,0xD7,0xF7],2,6);
r([0x16,0x36,0x56,0x76,0xD6,0xF6],2,6);
r([0xB6,0xB7,0x96,0x97],2,4); // zp,y
// abs
r([0x0D,0x2D,0x4D,0x6D,0xAD,0xCD,0xED,0xAE,0xAC,0xCC,0xEC,0x2C],3,4);
r([0x8D,0x8E,0x8C,0x8F],3,4);
r([0x0E,0x2E,0x4E,0x6E,0xCE,0xEE],3,6);
r([0x0F,0x2F,0x4F,0x6F,0xCF,0xEF],3,6);
r([0xAF],3,4); r([0x0C],3,4); // LAX abs, NOP abs
r([0x4C],3,3); r([0x20],3,6); r([0x6C],3,5);
// abs,x
r([0x1D,0x3D,0x5D,0x7D,0xBD,0xDD,0xFD,0xBC,0x1C,0x3C,0x5C,0x7C,0xDC,0xFC],3,4);
r([0x1E,0x3E,0x5E,0x7E,0xDE,0xFE],3,7);
r([0x1F,0x3F,0x5F,0x7F,0xDF,0xFF],3,7);
r([0x9D,0x9C],3,5); // STA abs,x / SHY abs,x
// abs,y
r([0x19,0x39,0x59,0x79,0xB9,0xD9,0xF9,0xBE,0xBF,0xBB],3,4);
r([0x1B,0x3B,0x5B,0x7B,0xDB,0xFB],3,7);
r([0x99,0x9B,0x9E,0x9F],3,5);
// (zp,x) (zp),y
r([0x01,0x21,0x41,0x61,0xA1,0xC1,0xE1,0x81,0x83],2,6);
r([0x03,0x23,0x43,0x63,0xC3,0xE3],2,8);
r([0x11,0x31,0x51,0x71,0xB1,0xD1,0xF1],2,5);
r([0x13,0x33,0x53,0x73,0xD3,0xF3],2,8);
r([0xB3],2,5); r([0xA3],2,6); r([0x91,0x93],2,6);
// branches
r([0x10,0x30,0x50,0x70,0x90,0xB0,0xD0,0xF0],2,2);

const bus = { m: new Uint8Array(0x10000), read(a) { return this.m[a]; }, write(a, v) { this.m[a] = v; } };
const c = new CPU(bus);
const PCLEN_SKIP = { 0x00: 1, 0x20: 1, 0x40: 1, 0x60: 1, 0x4C: 1, 0x6C: 1 };
function isBranch(op) { return (op & 0x1F) === 0x10; }
let bad = 0;
for (let op = 0; op < 256; op++) {
  if (LEN[op] === undefined) continue;
  bus.m.fill(0xEA);
  bus.m[0x8000] = op; bus.m[0x8001] = 0x00; bus.m[0x8002] = 0x02;
  bus.m[0x200] = 0x01;
  c.PC = 0x8000; c.A = 0; c.X = 0; c.Y = 0; c.P = 0x20; c.S = 0xF0;
  c.nmiPending = false; c.irqLine = false;
  const t0 = c.totalCycles;
  c.step();
  const len = c.PC - 0x8000;
  const cyc = c.totalCycles - t0;
  const lenOk = PCLEN_SKIP[op] ? true : (len === LEN[op]);
  const cycOk = isBranch(op) ? (cyc >= 2 && cyc <= 4) : (cyc === CYC[op]);
  if (!lenOk || !cycOk) {
    bad++;
    console.log(`op $${op.toString(16).padStart(2, '0')}: got len=${len} cyc=${cyc}, want len=${LEN[op]} cyc=${CYC[op]}`);
  }
}
// behavior spot checks
function beh(bytes, init, expect) {
  bus.m.fill(0xEA);
  bus.m.set(bytes, 0x8000);
  bus.m[0x200] = 0x01; bus.m[0x201] = 0xFF; bus.m[0x202] = 0x7F;
  Object.assign(c, { PC: 0x8000, A: 0, X: 0, Y: 0, P: 0x20, S: 0xF0, nmiPending: false, irqLine: false }, init);
  const t0 = c.totalCycles;
  for (let i = 0; i < (expect.steps || 1); i++) c.step();
  const got = { A: c.A, X: c.X, Y: c.Y, P: c.P, C: !!(c.P & 1), Z: !!(c.P & 2), N: !!(c.P & 0x80), V: !!(c.P & 0x40), cyc: c.totalCycles - t0, mem200: bus.m[0x200] };
  for (const k in expect) {
    if (k === 'steps') continue;
    if (got[k] !== expect[k]) { bad++; console.log(`behavior FAIL [${bytes.map(b => b.toString(16)).join(' ')}] ${k}: got ${got[k]} want ${expect[k]}`); }
  }
}
beh([0xA9, 0x50, 0x69, 0x50], {}, { steps: 2, A: 0xA0, V: true, N: true, C: false }); // ADC overflow
beh([0xA9, 0x50, 0xE9, 0xB0], { P: 0x21 }, { steps: 2, A: 0xA0, V: true, C: false }); // SBC overflow (C=1)
beh([0xA9, 0xFF, 0x69, 0x01], {}, { steps: 2, A: 0x00, Z: true, C: true, V: false });  // ADC carry
beh([0x4A], { A: 0x03 }, { A: 0x01, C: true });                                        // LSR A
beh([0x0A], { A: 0x80 }, { A: 0x00, C: true, Z: true });                               // ASL A
beh([0x2A], { A: 0x80, P: 0x21 }, { A: 0x01, C: true });                               // ROL A
beh([0x6A], { A: 0x01, P: 0x21 }, { A: 0x80, C: true, N: true });                      // ROR A
beh([0xC9, 0x05], { A: 0x05 }, { Z: true, C: true });                                  // CMP equal
beh([0xA5, 0x00], { }, { A: 0xEA });                                                   // LDA zp reads 0xEA fill
beh([0xA9, 0x01, 0x48, 0xA9, 0x02, 0x68], {}, { steps: 4, A: 0x01 });                  // PHA/PLA
beh([0x4C, 0x34, 0x12], { }, { A: 0 });                                                // JMP (checks below)

// JMP target check
bus.m.fill(0xEA);
bus.m[0x8000] = 0x4C; bus.m[0x8001] = 0x34; bus.m[0x8002] = 0x12;
c.PC = 0x8000; c.step();
if (c.PC !== 0x1234) { bad++; console.log('JMP FAIL: PC=$' + c.PC.toString(16)); }

// branch timing: taken same-page = 3, taken cross-page = 4
bus.m.fill(0xEA);
bus.m[0x80F8] = 0xD0; bus.m[0x80F9] = 0x7F; // BNE +0x7F (crosses page)
c.PC = 0x80F8; c.P = 0x20; let t0 = c.totalCycles; c.step();
if (c.totalCycles - t0 !== 4) { bad++; console.log('branch cross-page timing FAIL: ' + (c.totalCycles - t0)); }

console.log(bad === 0 ? 'CPU OPCODE SELF-TEST: ALL OK' : `CPU OPCODE SELF-TEST: ${bad} FAILURES`);
process.exit(bad === 0 ? 0 : 1);
